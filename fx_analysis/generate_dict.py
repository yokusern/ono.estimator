# ── ヘルパー関数 ─────────────────────────────────────────────────────────────

def _eval_mask(df, mask, direction, la, pf):
    idxs  = df.index[mask.fillna(False)]
    moves = []
    for idx in idxs:
        pos = df.index.searchsorted(idx)
        if pos + la >= len(df): continue
        m = (float(df["Close"].iloc[pos + la]) - float(df["Close"].iloc[pos])) / pf
        if direction == "sell": m = -m
        moves.append(m)
    if len(moves) < MIN_SAMP: return None
    wins   = [m for m in moves if m > 0]
    losses = [abs(m) for m in moves if m <= 0]
    wr = len(wins) / len(moves)
    aw = sum(wins) / len(wins) if wins else 0
    al = sum(losses) / len(losses) if losses else 0
    ev = wr * aw - (1 - wr) * al
    pf_val = sum(wins) / sum(losses) if losses else float("inf")
    return {"n": len(moves), "wr": wr * 100, "aw": aw, "al": al, "ev": ev, "pf": pf_val}

def _v(val, pair):
    return f"${val:+.0f}" if pair == "XAUUSD" else f"{val:+.1f}p"

def _wi(wr):
    if wr >= 80: return "🏆🏆"
    elif wr >= 72: return "🏆"
    elif wr >= 67: return "🟢"
    elif wr >= 62: return "🟡"
    elif wr >= 57: return "△"
    elif wr < 45:  return "🔴"
    else:           return "－"

