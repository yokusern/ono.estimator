def collect_all():
    """全ターゲットの分析データを収集して辞書で返す。"""
    results   = {}   # (pair, interval) → list of {label, dir, wr, ev, count, col}
    combos    = {}   # (pair, interval) → list of {label, dir, wr, ev, n}
    tf_best   = {}   # col → {(pair,interval): {wr, ev, n}} ── 時間足横断比較用
    all80plus = []   # 勝率80%以上のもの全部

    for pair, interval, period, la in TARGETS:
        pf = pip_factor(pair)
        key = (pair, interval)
        print(f"  [{pair} {interval}] ...", end="", flush=True)
        df = fetch(pair, interval, period)
        df = add_indicators(df)
        df = add_signals(df)
        df = add_patterns(df)
        df = add_context(df)
        print(f" {len(df):,}本")

        base_list = []
        for col, direction, label in ALL_DEFS:
            if col not in df.columns: continue
            r = evaluate(df, col, direction, la, pf)
            if r:
                row = {"col": col, "dir": direction, "label": label,
                       "wr": r["win_rate"], "ev": r["ev"],
                       "count": r["count"], "aw": r["avg_win"], "al": r["avg_loss"]}
                base_list.append(row)
                # 時間足横断
                if col not in tf_best: tf_best[col] = {}
                tf_best[col][key] = {"wr": r["win_rate"], "ev": r["ev"], "n": r["count"]}
                # 80%以上
                if r["win_rate"] >= 78:
                    all80plus.append({"pair": pair, "interval": interval,
                                      "label": label, "dir": direction,
                                      "wr": r["win_rate"], "ev": r["ev"], "n": r["count"]})
        base_list.sort(key=lambda x: -x["wr"])
        results[key] = base_list

        # 組み合わせ
        combo_list = []
        good = [r for r in base_list if r["ev"] > 0]
        for i, a in enumerate(good):
            for b in good[i+1:]:
                if a["col"] == b["col"] or a["dir"] != b["dir"]: continue
                mask = (df[a["col"]].fillna(False) & df[b["col"]].fillna(False))
                r = _eval_mask(df, mask, a["dir"], la, pf)
                if r and r["n"] >= MIN_SAMP:
                    combo_list.append({"label": f"{a['label']}  ＋  {b['label']}",
                                       "dir": a["dir"], **r})
                    if r["wr"] >= 78:
                        all80plus.append({"pair": pair, "interval": interval,
                                          "label": f"[組合せ] {a['label']} ＋ {b['label']}",
                                          "dir": a["dir"], "wr": r["wr"],
                                          "ev": r["ev"], "n": r["n"]})
        combo_list.sort(key=lambda x: -x["wr"])
        combos[key] = combo_list

    all80plus.sort(key=lambda x: -x["wr"])
    return results, combos, tf_best, all80plus

